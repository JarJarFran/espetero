def random_scenarios(n, seed):
    """Seeded random conversations mixing the features above."""
    rng = random.Random(seed)
    texts = ["Hi", "Explain quicksort briefly.", UNICODE_TEXT, "", "Multi\nline\n\ttext", "a <b> & 'c' \"d\"",
             "<think>\ninner\n</think>\n\nouter", "trailing space ", "  leading", "emoji 🎉"]
    tools_pool = [WEATHER_TOOL, SEARCH_TOOL, REF_TOOL, PLAIN_TOOL]
    out = []
    for k in range(n):
        msgs = []
        if rng.random() < 0.5:
            msgs.append({"role": "system", "content": rng.choice(texts[:3])})
        turns = rng.randint(1, 5)
        call_no = 0
        for _ in range(turns):
            if rng.random() < 0.2:
                msgs.append({"role": "user", "content": [{"type": "text", "text": rng.choice(texts)}] +
                             ([{"type": "image"}] if rng.random() < 0.5 else [])})
            else:
                msgs.append({"role": "user", "content": rng.choice(texts)})
            if rng.random() < 0.85:
                m = {"role": "assistant", "content": rng.choice(texts + [None])}
                if rng.random() < 0.3:
                    m["reasoning_content"] = rng.choice(["short reasoning", "multi\nline\nreasoning", ""])
                if rng.random() < 0.35:
                    calls = []
                    for _ in range(rng.randint(1, 2)):
                        call_no += 1
                        args = rng.choice([{"city": "Paris"}, {"query": "x", "limit": 3},
                                           {"expr": "1+1", "flag": False, "vals": [1, 2.5, None]}])
                        calls.append(tc(rng.choice(["get_weather", "web.search", "calc"]), args, f"c{call_no}",
                                        args_as_str=rng.random() < 0.3))
                    m["tool_calls"] = calls
                    msgs.append(m)
                    for c in calls:
                        msgs.append({"role": "tool", "content": rng.choice(["ok", '{"a": 1}', ""]),
                                     "tool_call_id": c["id"]})
                    if rng.random() < 0.7:
                        msgs.append({"role": "assistant", "content": rng.choice(texts)})
                else:
                    msgs.append(m)
        tools = rng.sample(tools_pool, rng.randint(1, 3)) if rng.random() < 0.4 else None
        out.append((f"random_{k:03d}", msgs, tools, {}))
    return out


