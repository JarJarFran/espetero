def collect_templates():
    """{sha: {"text", "sources"}} of every distinct non-empty chat template."""
    found = {}

    def add(text, src):
        if not isinstance(text, str) or not text.strip():
            return
        h = hashlib.sha256(text.encode("utf-8")).hexdigest()
        found.setdefault(h, {"text": text, "sources": []})["sources"].append(src)

    for root in SEARCH_ROOTS:
        for dp, _dns, fns in os.walk(root, followlinks=True):
            if "/.no_exist/" in dp + "/":  # hub cache markers for missing files
                continue
            for fn in sorted(fns):
                p = os.path.join(dp, fn)
                try:
                    if fn == "chat_template.jinja":
                        with open(p, encoding="utf-8") as f:
                            add(f.read(), p)
                    elif fn in ("tokenizer_config.json", "chat_template.json"):
                        with open(p, encoding="utf-8") as f:
                            d = json.load(f)
                        ct = d.get("chat_template")
                        if isinstance(ct, list):
                            for e in ct:
                                add(e.get("template"), p + "#" + str(e.get("name")))
                        else:
                            add(ct, p)
                except (OSError, ValueError) as e:
                    print("skip", p, e, file=sys.stderr)
    return found


def special_tokens_for(sources):
    """The tokenizer's special_tokens_map, read from a tokenizer_config.json next to a source."""
    keys = ["bos_token", "eos_token", "unk_token", "sep_token", "pad_token", "cls_token", "mask_token"]
    for src in sources:
        if src.startswith("synthetic:"):
            continue
        d = os.path.dirname(src.split("#")[0])
        p = os.path.join(d, "tokenizer_config.json")
        if not os.path.exists(p):
            continue
        try:
            with open(p, encoding="utf-8") as f:
                cfg = json.load(f)
        except (OSError, ValueError):
            continue
        out = {}
        for k in keys:
            v = cfg.get(k)
            if isinstance(v, dict):
                v = v.get("content")
            if isinstance(v, str):
                out[k] = v
        if out:
            return out
    return {"bos_token": "<s>", "eos_token": "</s>"}


