    found = collect_templates()
    manifest, cases, conversations, outputs = [], [], [], []
    conv_index, output_index = {}, {}

    def conv_id(name, msgs, tools):
        key = json.dumps([name, msgs, tools], sort_keys=True, ensure_ascii=False)
        if key not in conv_index:
            conv_index[key] = len(conversations)
            conversations.append({"name": name, "messages": msgs, "tools": tools})
        return conv_index[key]

    missing = sorted(v[0] for h, v in PUBLIC_TEMPLATES.items() if h not in found)
