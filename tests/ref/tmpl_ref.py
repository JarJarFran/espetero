def gen_unicode(path):
    def cat(cp):
        return unicodedata.category(chr(cp))

    def safe(f):
        return lambda cp: not (0xD800 <= cp <= 0xDFFF) and f(chr(cp))

    tables = {
        "kSpace": _ranges(safe(str.isspace)),
        "kNonPrintable": _ranges(lambda cp: not chr(cp).isprintable()),
        "kAlpha": _ranges(safe(str.isalpha)),
        "kDecimal": _ranges(safe(str.isdecimal)),
        "kDigit": _ranges(safe(str.isdigit)),
        "kNumeric": _ranges(safe(str.isnumeric)),
        "kLower": _ranges(safe(str.islower)),
        "kUpper": _ranges(safe(str.isupper)),
        "kTitle": _ranges(lambda cp: cat(cp) == "Lt"),
        "kCased": _ranges(lambda cp: not (0xD800 <= cp <= 0xDFFF)
                          and (chr(cp).islower() or chr(cp).isupper() or cat(cp) == "Lt")),
        "kCaseIgnorable": _ranges(lambda cp: cat(cp) in ("Mn", "Me", "Cf", "Lm", "Sk") or cp in _WB_MID),
    }
    lines = [
        "// SPDX-License-Identifier: Unicode-3.0",
        "// Derived from the Unicode Character Database, Copyright (c) 1991-2026 Unicode, Inc.,",
        "// Unicode License v3: see THIRD_PARTY_NOTICES.md.",
        "// Generated by tests/ref/tmpl_ref.py --gen-unicode from Python %s unicodedata %s. Do not edit."
        % (sys.version.split()[0], unicodedata.unidata_version),
        "// Inclusive code point ranges and case mapping runs (see unicode.cpp).",
        "",
    ]
    for name, rs in tables.items():
        lines.append("static const CpRange %s[] = {" % name)
        row = []
        for lo, hi in rs:
            row.append("{0x%X,0x%X}" % (lo, hi))
            if len(row) == 8:
                lines.append("  " + ",".join(row) + ",")
                row = []
        if row:
            lines.append("  " + ",".join(row) + ",")
        lines.append("};")
    for name, fn in (("Upper", str.upper), ("Lower", str.lower), ("Title", str.title)):
        single, full = _case_tables(fn)
        lines.append("static const CaseRun k%sRuns[] = {" % name)
        row = []
        for lo, hi, d, s in _runs(single):
            row.append("{0x%X,0x%X,%d,%d}" % (lo, hi, d, s))
            if len(row) == 6:
                lines.append("  " + ",".join(row) + ",")
                row = []
        if row:
            lines.append("  " + ",".join(row) + ",")
        lines.append("};")
        lines.append("static const CaseFull k%sFull[] = {" % name)
        for cp, m in full:
            m = m + [0] * (3 - len(m))
            lines.append("  {0x%X,{0x%X,0x%X,0x%X}}," % (cp, m[0], m[1], m[2]))
        lines.append("};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


