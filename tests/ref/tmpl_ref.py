def tc(name, args, id_=None, wrap=True, args_as_str=False):
    a = json.dumps(args, ensure_ascii=False) if args_as_str else args
    call = {"name": name, "arguments": a}
    out = {"type": "function", "function": call} if wrap else dict(call)
    if id_:
        out["id"] = id_
    return out


