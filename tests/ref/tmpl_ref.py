def build_snippets():
    from transformers.utils.chat_template_utils import _compile_jinja_template

    os.makedirs(FIXTURES, exist_ok=True)
    out = []
    for src, ctx in SNIPPETS:
        try:
            out.append({"source": src, "context": ctx, "expect": _compile_jinja_template(src).render(**ctx)})
        except Exception as e:
            out.append({"source": src, "context": ctx, "error": {"type": type(e).__name__, "message": str(e)}})
    with open(os.path.join(FIXTURES, "snippets.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    return out


def main():
    global FIXTURES
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gen-unicode", metavar="OUT", help="write the Unicode tables for src/tmpl/unicode.cpp")
    ap.add_argument("--random", type=int, default=40, help="random conversations per template")
    ap.add_argument("--out", default=FIXTURES, help="output directory (default: tests/ref/tmpl_fixtures)")
    args = ap.parse_args()
    FIXTURES = args.out
    if args.gen_unicode:
        gen_unicode(args.gen_unicode)
        return
