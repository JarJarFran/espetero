def _ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def _case_tables(fn):
    """Single code point mappings as (cp, delta) and multi code point ones."""
    single, full = [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if m == c:
            continue
        if len(m) == 1:
            single.append((cp, ord(m) - cp))
        else:
            assert len(m) <= 3, (hex(cp), m)
            full.append((cp, [ord(x) for x in m]))
    return single, full


def _runs(pairs):
    """Compress sorted (cp, delta) into (lo, hi, delta, stride) runs."""
    out = []
    i = 0
    while i < len(pairs):
        lo, d = pairs[i]
        hi, stride, j = lo, 1, i + 1
        if j < len(pairs) and pairs[j][1] == d and pairs[j][0] - lo in (1, 2):
            stride = pairs[j][0] - lo
            while j < len(pairs) and pairs[j][1] == d and pairs[j][0] == hi + stride:
                hi = pairs[j][0]
                j += 1
        out.append((lo, hi, d, stride))
        i = j
    return out


