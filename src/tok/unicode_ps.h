// Whether cp is in \p{P} or \p{S}.
inline bool is_punct_symbol(uint32_t cp) {
  uint32_t lo = 0, hi = kNumPS;  // first boundary > cp
  while (lo < hi) {
    const uint32_t mid = (lo + hi) >> 1;
    if (kPS[mid] <= cp) lo = mid + 1;
    else hi = mid;
  }
  return lo % 2 == 1;
}

